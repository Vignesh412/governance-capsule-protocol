    APPROVAL_EXPIRED = "GCP_APPROVAL_EXPIRED"
    APPROVAL_NOT_YET_VALID = "GCP_APPROVAL_NOT_YET_VALID"
    UNAUTHORIZED_APPROVER = "GCP_UNAUTHORIZED_APPROVER"
    UNAUTHORIZED_AMENDMENT = "GCP_UNAUTHORIZED_AMENDMENT"
    AMENDMENT_MISMATCH = "GCP_AMENDMENT_MISMATCH"
    INVALID_GOVERNANCE_GRAPH = "GCP_INVALID_GOVERNANCE_GRAPH"
